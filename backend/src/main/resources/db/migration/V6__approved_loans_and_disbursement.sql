CREATE TABLE loans (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    application_id UUID NOT NULL UNIQUE REFERENCES loan_applications(id) ON DELETE RESTRICT,
    borrower_id UUID NOT NULL REFERENCES borrower_profiles(user_id) ON DELETE RESTRICT,
    principal NUMERIC(30,2) NOT NULL CHECK (principal > 0),
    flat_rate_percent NUMERIC(30,10) NOT NULL CHECK (flat_rate_percent >= 0),
    term_months INTEGER NOT NULL CHECK (term_months > 0),
    interest_amount NUMERIC(30,2) NOT NULL CHECK (interest_amount >= 0),
    total_repayable NUMERIC(30,2) NOT NULL CHECK (total_repayable = principal + interest_amount),
    outstanding_balance NUMERIC(30,2) NOT NULL CHECK (outstanding_balance >= 0),
    status VARCHAR(16) NOT NULL DEFAULT 'APPROVED'
        CHECK (status IN ('APPROVED','DISBURSED','ACTIVE','COMPLETED')),
    approved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    disbursed_at TIMESTAMPTZ,
    activated_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX loans_borrower_status_idx ON loans (borrower_id,status,approved_at DESC);

CREATE TABLE disbursements (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    loan_id UUID NOT NULL UNIQUE REFERENCES loans(id) ON DELETE RESTRICT,
    amount NUMERIC(30,2) NOT NULL CHECK (amount > 0),
    recorded_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE loan_status_history (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    loan_id UUID NOT NULL REFERENCES loans(id) ON DELETE RESTRICT,
    from_status VARCHAR(16),
    to_status VARCHAR(16) NOT NULL,
    changed_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT loan_status_history_from_check CHECK (
        from_status IS NULL OR from_status IN ('APPROVED','DISBURSED','ACTIVE','COMPLETED')
    ),
    CONSTRAINT loan_status_history_to_check CHECK (to_status IN ('APPROVED','DISBURSED','ACTIVE','COMPLETED'))
);

CREATE INDEX loan_status_history_loan_changed_idx ON loan_status_history (loan_id,sequence_id);
